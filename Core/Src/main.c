/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_CAN1_Init();
  MX_CAN2_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  
  //出力の配列
  int16_t pwm[4] = {0, 0, 0, 0};
  uint8_t servo[8] = {0, 0, 0, 0, 0, 0, 0, 0};

  //モータの出力値
  int16_t susumi = -6000;
  int16_t modori = 8000;
  //サーボの回転角
  uint8_t servo_output = 64;  // (45 / 180)*255 = 63.75

  //最終出力値
  int16_t fin_don_output = 0;
  uint8_t fin_servo_output = 0;

  //CANID
  const uint32_t don_id = 4;
  const uint32_t servo_id = 140;

  //制御周期
  int TxInterval = 10; // ms

  //ボタン押し回数
  int mode = 0;
  int maxMode = 7;

  //前回のボタン押し状態
  uint8_t pre = 0;

  while (1)
  {
    uint8_t now = !HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13);

    // 立ち上がりエッジのみ検出する
    if(now && !pre){
      mode++;
      if(mode > maxMode){
        mode = 0;
      }
    }

    /*
    ＜モードの説明＞
    0. 丼停止、サーボ0  (初期状態)
    1. 丼停止、サーボ角度 (サーボ準備)
    2. 丼正転、サーボ角度 (回収)
    3. 丼停止、サーボ角度 (回収完了)
    4. 丼逆転、サーボ角度  (放出)
    5. 丼停止、サーボ角度　(放出完了・一時停止)
    6. 丼停止、サーボ0　(リロード)
    7. 0に戻る
    
    */

    switch(mode){
      case 0:
      //丼停止、サーボ0
        fin_don_output = 0;
        fin_servo_output = 0;
        break;
      case 1:
      //丼停止、サーボ角度
       fin_don_output = 0;
       fin_servo_output = servo_output;
        break;
      case 2:
      //丼正転、サーボ角度
        fin_don_output = susumi;
        fin_servo_output = servo_output;
        break;
      case 3:
      //丼停止、サーボ角度
        fin_don_output = 0;
        fin_servo_output = servo_output;
        break;
      case 4:
      //丼逆転、サーボ角度
        fin_don_output = modori;
        fin_servo_output = servo_output;
        break;
      case 5:
      //丼停止、サーボ角度
        fin_don_output = 0;
        fin_servo_output = servo_output;
        break;
      case 6:
      //丼停止、サーボ0
        fin_don_output = 0;
        fin_servo_output = 0;
        break;
      case 7:
        fin_don_output = 0;
        fin_servo_output = 0;
        mode = 0;
        break;
      default:
        fin_don_output = 0;
        fin_servo_output = 0;
        mode = 0;
        break; 
    }

  
    //出力値を配列に格納
    for(int i = 0; i < 4; i++) {
      pwm[i] = fin_don_output;
    }

    for(int i = 0; i < 8; i++) {
      servo[i] = fin_servo_output;
    }

    //現在の出力を表示
    printf("don=%d, servo=%d\r\n", fin_don_output, fin_servo_output);

    CANSend(&hcan1, don_id, (const uint8_t *)pwm, 8);
    CANSend(&hcan2, don_id, (const uint8_t *)pwm, 8);

    CANSend(&hcan1, servo_id, servo, 8);
    CANSend(&hcan2, servo_id, servo, 8);

    // printf("mode=%d, don=%d, servo=%d\r\n", mode, fin_don_output, fin_servo_output);

    pre = now; 
    HAL_Delay(TxInterval); 
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

